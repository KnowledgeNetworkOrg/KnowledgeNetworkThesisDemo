// WHICH CORPUS THE APP IS LOOKING AT. Every instrument, model and view in this
// repo imports its graph from here and has done since before there was more
// than one; the names and shapes below are exactly what they have always been.
// What changed is that the DATA is no longer written in this file.
//
// Two corpora ship:
//
//   teaching (default)  the hand-authored CS teaching corpus — `teachingdata.ts`.
//                       Six domains, sixteen modules, 53 topics, 116 authored
//                       edges. Every pinned test in the repo measures this one.
//
//   cs2023              the knowledge areas and units of Computer Science
//                       Curricula 2023 — `cs2023data.ts`, GENERATED by
//                       `tools/cs2023import/` from the thesis's map file. Its
//                       "topics" are knowledge units, and its only edges are
//                       CS2023's own printed "See also" notes.
//
// CHOOSING ONE: the address's `?corpus=cs2023` wins; failing that
// `VITE_CORPUS=cs2023 npm run dev` (or the same variable in front of
// `npm run build`); failing that teaching, so every existing script, test and
// screenshot run behaves as before. Both corpora ship in every build and the
// choice is made once, at load: the corpus is a module-level constant that forty
// files import directly, so the header's switch reloads the page rather than
// swapping it while the app is running — a different and much larger change.

